public class Basic {
    public static void main(String[] args){
        int x = -67;
        int y = 33;


        System.out.println("x + y = " + (x + y));

        System.out.println("x * y = " + (x * y));

        System.out.println("x - y = " + (x - y));

        System.out.println("x / y = " + (x / y));

        System.out.println("x % y = " + (x % y));
        // % keeps the negative sign even though its a remainder.




    }
}
